/* Self-check for sweep-plan.js — run: node sweep-plan.test.js */
"use strict";
var assert = require("assert");
var P = require("./sweep-plan.js");

// decAdd: exact decimal strings, deep fractions, carries
assert.strictEqual(P.decAdd("1", "2"), "3");
assert.strictEqual(P.decAdd("0.1", "0.2"), "0.3");                       // the float classic
assert.strictEqual(P.decAdd("999.999", "0.001"), "1000");
assert.strictEqual(P.decAdd("0.00000000000000000000000000000000000000000001", "1"),
                   "1.00000000000000000000000000000000000000000001");    // 44 decimals
assert.strictEqual(P.decAdd("0", "0"), "0");

// coinAmount: token coins move token units, Minima coins move amount
assert.strictEqual(P.coinAmount({ tokenid: "0x00", amount: "5.5" }), "5.5");
assert.strictEqual(P.coinAmount({ tokenid: "0xAB", amount: "0.005", tokenamount: "50" }), "50");

// stateEntries: array and object forms
assert.deepStrictEqual(P.stateEntries({ state: [{ port: 0, type: 1, data: "0xFF" }] }),
                       [{ port: "0", data: "0xFF" }]);
assert.deepStrictEqual(P.stateEntries({ state: { "2": "hello" } }), [{ port: "2", data: "hello" }]);
assert.deepStrictEqual(P.stateEntries({}), []);

function coin(id, addr, amount, tokenid, extra) {
  var c = { coinid: id, address: addr, amount: amount, tokenid: tokenid || "0x00", spent: false };
  if (extra) Object.keys(extra).forEach(function (k) { c[k] = extra[k]; });
  return c;
}
var OWN = { "0XAAA": true, "0XBBB": true, "0XCCC": true, "0XDDD": true, "0XEEE": true, "0XFFF": true };

// plan: skip foreign addresses and spent coins
var p = P.plan([coin("0x01", "0xaaa", "1"), coin("0x02", "0xZZZ", "1"),
                coin("0x03", "0xaaa", "1", "0x00", { spent: true })], OWN);
assert.strictEqual(p.jobs.length, 1);
assert.strictEqual(p.skipped.length, 1);
assert.strictEqual(P.jobSum(p.jobs[0]), "1");

// plan: plain token pooled, state coin whole, scripted token whole
var tokPlain = { name: "PLAIN", script: "RETURN TRUE" };
var tokScripted = { name: "LOCKED", script: "RETURN SIGNEDBY(0x99)" };
p = P.plan([
  coin("0x10", "0xaaa", "0.001", "0xT1", { tokenamount: "10", token: tokPlain }),
  coin("0x11", "0xbbb", "0.002", "0xT1", { tokenamount: "20", token: tokPlain }),
  coin("0x12", "0xaaa", "0.001", "0xT2", { tokenamount: "1", token: tokScripted }),
  coin("0x13", "0xaaa", "0.001", "0xT1", { tokenamount: "5", token: tokPlain,
       state: [{ port: 0, type: 2, data: "owner" }] }),
  coin("0x14", "0xaaa", "3")
], OWN);
// jobs: 2 wholes (scripted + stated) first, then 1 pooled token chunk, then 1 Minima chunk
assert.strictEqual(p.jobs.length, 4);
assert.strictEqual(p.jobs[0].whole, true);
assert.strictEqual(p.jobs[1].whole, true);
assert.deepStrictEqual(p.jobs[1].states, [{ port: "0", data: "owner" }]);
assert.strictEqual(P.jobSum(p.jobs[2]), "30");       // token units, exact
assert.strictEqual(P.jobSum(p.jobs[3]), "3");
assert.strictEqual(p.signatures, 2 + 2 + 1);         // wholes:2, token chunk 2 addrs, minima 1 addr

// chunking: 25 same-address coins -> 10 + 10 + 5 (input cap)
var many = [];
for (var i = 0; i < 25; i++) many.push(coin("0xC" + i, "0xaaa", "1"));
p = P.plan(many, OWN);
assert.deepStrictEqual(p.jobs.map(function (j) { return j.coins.length; }), [10, 10, 5]);
assert.strictEqual(p.signatures, 3);                 // one address, one sig per chunk

// chunking: 6 coins at 6 addresses -> each new key costs ~9K of signature budget, so the
// 48K byte budget flushes at 3 keys, before the 4-key cap (same arithmetic as the APK)
var spread = ["0xaaa", "0xbbb", "0xccc", "0xddd", "0xeee", "0xfff"].map(function (a, i) {
  return coin("0xD" + i, a, "1");
});
p = P.plan(spread, OWN);
assert.deepStrictEqual(p.jobs.map(function (j) { return j.coins.length; }), [3, 3]);
assert.strictEqual(p.signatures, 6);

// split halves a pooled job without losing coins
var halves = P.split(p.jobs[0]);
assert.strictEqual(halves[0].coins.length + halves[1].coins.length, p.jobs[0].coins.length);

// size refusal detection
assert.ok(P.isSizeRefusal("TxPoW size too large 68000/65536"));
assert.ok(!P.isSizeRefusal("Insufficient funds"));

// Mx destination validation — golden vector generated BY A LIVE NODE (minima 1.1.2.4
// `scripts` row, 2026-10-19; the commented vector in core Address.java main() is stale).
global.sha3_256 = require("./sha3.js").sha3_256;
var D = require("./derive.js");
var mxDeps = { fromHex: D._fromHex, encode32: D._encode32, sha3: global.sha3_256 };
var mx = P.mxFromHex("0xC2585B2A52C6FF475D28C901D31E482FE0071872E5C2229A8E6E23422D471FC2", mxDeps);
assert.strictEqual(mx, "MxG0862B1DWKKM6VT3YQA69079HSW1FS03HGSN5Z8H9Y3JE4D12QHZVZ82GNCRG");
assert.ok(P.MX_RE.test(mx));
assert.ok(!P.MX_RE.test("0xC2585B2A"));                        // hex is not an Mx address
assert.ok(!P.MX_RE.test("MxG086ILO"));                         // I, L, O never appear in base32-remap
assert.ok(P.mxFromHex("0xC2585B2A52C6FF475D28C901D31E482FE0071872E5C2229A8E6E23422D471FC3", mxDeps) !== mx); // 1-byte change breaks the checksum match

// validateDestination: Mx-only + checksum + EXISTS in the derived block set — or refused
var goodDest = { index: 3, address: "0xC2585B2A52C6FF475D28C901D31E482FE0071872E5C2229A8E6E23422D471FC2",
                 miniaddress: "MxG0862B1DWKKM6VT3YQA69079HSW1FS03HGSN5Z8H9Y3JE4D12QHZVZ82GNCRG" };
var blockSet = [ { index: 0, address: "0xAA", miniaddress: "MxAA" }, goodDest ];
assert.strictEqual(P.validateDestination(goodDest, blockSet, mxDeps), null);
assert.ok(/not a well-formed Mx/.test(P.validateDestination(
  { index: 3, address: goodDest.address, miniaddress: goodDest.address }, blockSet, mxDeps)));  // 0x form refused
assert.ok(/checksum does not match/.test(P.validateDestination(
  { index: 3, address: "0xC2585B2A52C6FF475D28C901D31E482FE0071872E5C2229A8E6E23422D471FC3",
    miniaddress: goodDest.miniaddress }, blockSet, mxDeps)));                                   // wrong hex refused
assert.ok(/not one of this seed/.test(P.validateDestination(
  { index: 9, address: goodDest.address, miniaddress: goodDest.miniaddress }, blockSet, mxDeps))); // wrong index = not in set
assert.ok(/not one of this seed/.test(P.validateDestination(goodDest, [], mxDeps)));            // empty set refused
assert.ok(P.validateDestination(null, blockSet, mxDeps) !== null);                              // no destination refused

// size-aware chunking (ported from SweepFlow 0.2.23): a fat coin forces a byte-budget flush
function fatCoin(id, addr, stateBytes) {
  var c = coin(id, addr, "1");
  c.state = [{ port: "0", data: "F".repeat(stateBytes * 2) }];   // 2 hex chars per byte
  return c;
}
// 5 coins ~10K serialized each (~22K chunk cost each incl. proof copy + overhead) at ONE
// address: input/key caps alone would pool all 5, the 48K budget must flush earlier.
var fat = [1, 2, 3, 4, 5].map(function (i) { return fatCoin("0xF" + i, "0xaaa", 10 * 1024); });
p = P.plan(fat, OWN);
assert.ok(p.jobs.length >= 2, "byte budget must split fat coins (got " + p.jobs.length + " job(s))");
p.jobs.forEach(function (j) { assert.ok(j.coins.length < 5); });

// an oversized SINGLE whole (state coin past the budget) is planned LAST with a warning
var bigNft = fatCoin("0xB1", "0xaaa", 30 * 1024);               // ~30K coin -> est ~100K > 48K
bigNft.tokenid = "0xDEAD";
bigNft.token = { name: "BigPlate", script: "RETURN TRUE" };
var mix = [coin("0xC1", "0xaaa", "5"), bigNft];
p = P.plan(mix, OWN);
assert.strictEqual(p.oversized.length, 1);
assert.ok(/attempted last/.test(p.oversized[0]));
assert.strictEqual(p.jobs[p.jobs.length - 1].coins[0].coinid, "0xB1"); // heavy single is the LAST job
assert.ok(p.jobs[p.jobs.length - 1].whole);
// a normal-size whole still plans normally with no warning
var smallNft = coin("0xC2", "0xaaa", "1");
smallNft.tokenid = "0xBEEF";
smallNft.token = { name: "SmallNft", script: "RETURN TRUE" };
smallNft.state = [{ port: "0", data: "0x01" }];
p = P.plan([smallNft], OWN);
assert.strictEqual(p.oversized.length, 0);
assert.strictEqual(p.jobs.length, 1);
assert.ok(p.jobs[0].whole);

// runJob watchdog — exercised on the REAL code extracted from index.html (mds.js never
// calls back on an HTTP error, so a silent node must fail the job, once, not wedge it).
var src = require("fs").readFileSync(__dirname + "/index.html", "utf8");
var m = src.match(/var CMD_TIMEOUT_MS[\s\S]*?\n}\n\n\/\* -+ confirm on-chain/);
assert.ok(m, "runJob block found in index.html");
var runJobSrc = m[0].replace(/\n}\n\n\/\* -+ confirm on-chain$/, "\n}")
                    .replace("120000", "150");          // shrink the watchdog for the test
function harness(mdsCmd) {
  var sandbox = { MDS: { cmd: mdsCmd }, SweepPlan: P, destKey: goodDest,
                  setTimeout: setTimeout, clearTimeout: clearTimeout, Date: Date, Math: Math, String: String };
  require("vm").createContext(sandbox);
  require("vm").runInContext(runJobSrc, sandbox);
  return sandbox.runJob;
}
var job1 = { whole: false, tokenid: "0x00", coins: [coin("0xE1", "0xaaa", "1")], label: "t" };
var calls = [];
// 1. silent node: no callback ever -> watchdog fails the job exactly once, txndelete attempted
harness(function (c, cb) { calls.push(c); /* never calls back */ })(job1, function (ok, why) {
  assert.strictEqual(ok, false);
  assert.ok(/did not respond/.test(why));
  setTimeout(function () {
    assert.ok(calls.some(function (c) { return c.indexOf("txndelete") === 0; }), "cleanup txndelete issued");

    // 2. happy path: every command succeeds -> cb(true, txpowid) exactly once
    var n = 0;
    harness(function (c, cb) { cb({ status: true, response: { txpow: { txpowid: "0xT1" } } }); })(
      job1, function (ok, id) {
        n++;
        assert.strictEqual(ok, true); assert.strictEqual(id, "0xT1"); assert.strictEqual(n, 1);

        // 3. command error -> txndelete runs, cb(false) exactly once even with a late extra reply
        var seq = [], cbs = 0;
        harness(function (c, cb) {
          seq.push(c);
          cb(c.indexOf("txndelete") === 0 ? { status: true } : { status: false, error: "boom" });
        })(job1, function (ok2, why2) {
          cbs++;
          assert.strictEqual(ok2, false); assert.ok(/boom/.test(why2)); assert.strictEqual(cbs, 1);
          assert.ok(seq.some(function (c) { return c.indexOf("txndelete") === 0; }));
          console.log("sweep-plan.test.js: all checks passed");
        });
      });
  }, 250);
});
